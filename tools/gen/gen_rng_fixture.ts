// Generates the RNG parity fixture consumed by tests/test_rng.gd.
//
// Run from the ALPHA repo so its node_modules resolve, but this file lives in
// the BETA repo so the alpha stays untouched (D-003, D-010):
//
//   cd C:\Users\chode\breach
//   node_modules/.bin/tsx ../1C38R34KR/tools/gen/gen_rng_fixture.ts
//
// Values are captured as raw uint32 rather than the [0,1) float that next()
// returns. next() divides by 2^32, so the uint32 is recoverable exactly
// (the divisor is a power of two, so no precision is lost), and comparing
// integers sidesteps every float-formatting difference between JS and GDScript.
//
// D-009: this fixture is the gate on the whole build. If GDScript cannot
// reproduce it exactly, nothing downstream is trustworthy.

import { writeFileSync } from 'node:fs';
import { makeRNG } from '../../../breach/src/logic/rng';

const TWO32 = 4294967296;
const SEEDS = [0, 1, 1337, 2147483647];
const DRAWS = 1000;
const STATE_CHECKPOINTS = [1, 10, 100, 1000];

// next() returns u32 / 2^32; recover the exact integer.
const u32of = (v: number): number => Math.round(v * TWO32);

interface SeedVector {
  seed: number;
  draws: number[];        // raw uint32, in order
  states: Record<string, number>; // getState() after N draws
}

function vectorFor(seed: number): SeedVector {
  const rng = makeRNG(seed);
  const draws: number[] = [];
  const states: Record<string, number> = {};
  for (let i = 1; i <= DRAWS; i++) {
    draws.push(u32of(rng.next()));
    if (STATE_CHECKPOINTS.includes(i)) states[String(i)] = rng.getState();
  }
  return { seed, draws, states };
}

// int(n) = floor(next() * n). Worth pinning separately: it is the form the
// game actually calls, and an off-by-one in the floor would not show up in
// the raw draw comparison.
function intSamples(): Record<string, number[]> {
  const out: Record<string, number[]> = {};
  for (const n of [2, 3, 6, 8, 36, 64, 100]) {
    const rng = makeRNG(1337);
    out[String(n)] = Array.from({ length: 20 }, () => rng.int(n));
  }
  return out;
}

// Fisher-Yates consumes draws in a specific order; a port that iterates the
// other direction produces a different permutation from the same sequence.
function shuffleSamples(): Record<string, number[]> {
  const out: Record<string, number[]> = {};
  for (const seed of SEEDS) {
    const rng = makeRNG(seed);
    out[String(seed)] = rng.shuffle(Array.from({ length: 16 }, (_, i) => i));
  }
  return out;
}

// resume: makeRNG(getState()) must continue the identical sequence.
function resumeSample(): { seed: number; before: number[]; state: number; after: number[] } {
  const rng = makeRNG(1337);
  const before = Array.from({ length: 50 }, () => u32of(rng.next()));
  const state = rng.getState();
  const after = Array.from({ length: 50 }, () => u32of(rng.next()));
  return { seed: 1337, before, state, after };
}

const fixture = {
  _comment: 'Generated by tools/gen/gen_rng_fixture.ts from the alpha mulberry32. Do not hand-edit.',
  algorithm: 'mulberry32',
  source: 'breach/src/logic/rng.ts',
  draws: DRAWS,
  vectors: SEEDS.map(vectorFor),
  int_samples: intSamples(),
  shuffle_samples: shuffleSamples(),
  resume: resumeSample(),
};

const out = process.argv[2] ?? '../1C38R34KR/tests/fixtures/rng_vectors.json';
writeFileSync(out, JSON.stringify(fixture, null, 2) + '\n');
console.log(`wrote ${out}`);
console.log(`seeds: ${SEEDS.join(', ')} | draws each: ${DRAWS}`);
for (const v of fixture.vectors) {
  console.log(`  seed ${String(v.seed).padStart(10)}  first=${v.draws[0]}  last=${v.draws[DRAWS - 1]}  state@1000=${v.states['1000']}`);
}
