// Generates the engine-constant parity fixture consumed by tests/test_constants.gd.
//
//   cd C:\Users\chode\breach
//   node_modules/.bin/tsx ../1C38R34KR/tools/gen/gen_constants_fixture.ts
//
// Authorization §12 forbids balance changes during the port. That is easy to
// state and easy to violate by mistranscribing one number, so it is checked
// mechanically rather than trusted: every gameplay-affecting engine constant
// and every default battle setting is dumped here and compared in GDScript.
//
// Constants are emitted under their ALPHA names. The GDScript test maps them to
// its snake_case equivalents explicitly, so the naming translation stays
// visible and auditable instead of being assumed.

import { writeFileSync } from 'node:fs';
import * as C from '../../../breach/src/logic/constants';

const constants: Record<string, unknown> = {};
for (const [key, value] of Object.entries(C)) {
  if (typeof value === 'function') continue; // isStrongColor / isStrongShape
  constants[key] = value;
}

const fixture = {
  _comment: 'Generated by tools/gen/gen_constants_fixture.ts from the alpha. Do not hand-edit.',
  source: 'breach/src/logic/constants.ts',
  constants,
};

const out = process.argv[2] ?? '../1C38R34KR/tests/fixtures/constants.json';
writeFileSync(out, JSON.stringify(fixture, null, 2) + '\n');
console.log(`wrote ${out}`);
for (const [k, v] of Object.entries(constants)) {
  console.log(`  ${k} = ${JSON.stringify(v)}`);
}
